const valorA: number = 12;
const valorB: number = 4;
const valorC: number = 2

const resultadoSemParenteses = valorA + valorB * valorC;
const resultadoComParenteses = (valorA + valorB) * valorC;

console.log(`Sem parênteses: ${resultadoSemParenteses}`);
console.log(`Com parêntessis: ${resultadoComParenteses}`);
